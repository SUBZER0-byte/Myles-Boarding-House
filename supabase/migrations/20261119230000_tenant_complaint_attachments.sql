CREATE OR REPLACE FUNCTION public.attach_tenant_complaint_attachments(
    p_complaint_id integer,
    p_attachments jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    app_user_id integer;
    app_tenant_id integer;
    attachment_item jsonb;
    attachment_path text;
    attachment_kind text;
    attachment_mime text;
    attachment_size bigint;
    attachment_order integer;
    image_count integer;
    video_count integer;
    attachment_count integer;
BEGIN
    IF public.current_app_user_role() IS DISTINCT FROM 'Tenant' THEN
        RAISE EXCEPTION 'Tenant access is required.';
    END IF;

    app_user_id := public.current_app_user_id();
    SELECT tenant."tenant_id"
      INTO app_tenant_id
      FROM public.tenants AS tenant
     WHERE tenant."user_id" = app_user_id
       AND tenant."is_active" = 1
     ORDER BY tenant."tenant_id" DESC
     LIMIT 1;
    IF app_tenant_id IS NULL THEN
        RAISE EXCEPTION 'Active tenant record not found.';
    END IF;

    IF p_attachments IS NULL OR jsonb_typeof(p_attachments) IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'Choose valid complaint attachments.';
    END IF;
    attachment_count := jsonb_array_length(p_attachments);
    SELECT count(*) FILTER (WHERE value ->> 'type' = 'image'),
           count(*) FILTER (WHERE value ->> 'type' = 'video')
      INTO image_count, video_count
      FROM jsonb_array_elements(p_attachments);
    IF attachment_count < 1 OR attachment_count > 6
       OR image_count > 5 OR video_count > 1
       OR image_count + video_count <> attachment_count THEN
        RAISE EXCEPTION 'Attach up to five images and one optional video.';
    END IF;

    PERFORM 1
      FROM public.complaints AS complaint
     WHERE complaint."complaint_id" = p_complaint_id
       AND complaint."tenant_id" = app_tenant_id
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Complaint not found for this tenant.';
    END IF;

    FOR attachment_item IN
        SELECT value FROM jsonb_array_elements(p_attachments)
    LOOP
        attachment_path := attachment_item ->> 'path';
        attachment_kind := attachment_item ->> 'type';
        IF attachment_path IS NULL OR length(attachment_path) > 1024
           OR attachment_kind IS NULL OR attachment_kind NOT IN ('image', 'video')
           OR COALESCE(attachment_item ->> 'sort_order', '') !~ '^\d{1,2}$' THEN
            RAISE EXCEPTION 'Choose valid complaint attachments.';
        END IF;
        attachment_order := (attachment_item ->> 'sort_order')::integer;
        IF attachment_order < 0 OR attachment_order > 5
           OR (storage.foldername(attachment_path))[1] IS DISTINCT FROM auth.uid()::text THEN
            RAISE EXCEPTION 'The uploaded complaint attachment is invalid.';
        END IF;

        SELECT object_file.metadata ->> 'mimetype',
               COALESCE(NULLIF(object_file.metadata ->> 'size', '')::bigint, 0)
          INTO attachment_mime, attachment_size
          FROM storage.objects AS object_file
         WHERE object_file."bucket_id" = 'mbh-request-photos'
           AND object_file."name" = attachment_path;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'The uploaded complaint attachment could not be found.';
        END IF;

        IF attachment_kind = 'image' THEN
            IF attachment_mime NOT IN ('image/jpeg', 'image/png', 'image/webp')
               OR attachment_size < 1 OR attachment_size > 10485760 THEN
                RAISE EXCEPTION 'Images must be JPG, PNG, or WEBP and 10MB or smaller.';
            END IF;
        ELSIF attachment_mime NOT IN ('video/mp4', 'video/webm', 'video/quicktime')
           OR attachment_size < 1 OR attachment_size > 52428800 THEN
            RAISE EXCEPTION 'Video must be MP4, WEBM, or MOV and 50MB or smaller.';
        END IF;

        INSERT INTO public.complaint_attachments (
            complaint_id, storage_path, attachment_type, sort_order
        )
        VALUES (
            p_complaint_id, attachment_path, attachment_kind, attachment_order
        );
    END LOOP;

    RETURN jsonb_build_object('type', 'success', 'message', 'Attachments saved.');
END;
$$;

CREATE OR REPLACE FUNCTION public.list_tenant_complaint_attachments()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    app_user_id integer;
    app_tenant_id integer;
    result_data jsonb;
BEGIN
    IF public.current_app_user_role() IS DISTINCT FROM 'Tenant' THEN
        RAISE EXCEPTION 'Tenant access is required.';
    END IF;
    app_user_id := public.current_app_user_id();
    SELECT tenant."tenant_id"
      INTO app_tenant_id
      FROM public.tenants AS tenant
     WHERE tenant."user_id" = app_user_id
       AND tenant."is_active" = 1
     ORDER BY tenant."tenant_id" DESC
     LIMIT 1;
    IF app_tenant_id IS NULL THEN
        RAISE EXCEPTION 'Active tenant record not found.';
    END IF;

    SELECT COALESCE(
        jsonb_agg(jsonb_build_object(
            'attachment_id', attachment.attachment_id,
            'complaint_id', attachment.complaint_id,
            'path', attachment.storage_path,
            'type', attachment.attachment_type,
            'sort_order', attachment.sort_order
        ) ORDER BY complaint."created_at" DESC, attachment.sort_order),
        '[]'::jsonb
    )
      INTO result_data
      FROM public.complaint_attachments AS attachment
      JOIN public.complaints AS complaint
        ON complaint."complaint_id" = attachment.complaint_id
     WHERE complaint."tenant_id" = app_tenant_id;
    RETURN result_data;
END;
$$;

