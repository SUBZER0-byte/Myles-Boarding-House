   SET public = false,
       file_size_limit = 52428800,
       allowed_mime_types = ARRAY[
           'image/jpeg',
           'image/png',
           'image/webp',
           'video/mp4',
           'video/webm',
           'video/quicktime'
       ]
 WHERE id = 'mbh-request-photos';

CREATE TABLE IF NOT EXISTS public.complaint_attachments (
    attachment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id integer NOT NULL
        REFERENCES public.complaints ("complaint_id") ON DELETE CASCADE,
    storage_path text NOT NULL UNIQUE,
    attachment_type text NOT NULL CHECK (attachment_type IN ('image', 'video')),
    sort_order smallint NOT NULL CHECK (sort_order BETWEEN 0 AND 5),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (complaint_id, sort_order)
);

ALTER TABLE public.complaint_attachments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.complaint_attachments FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.is_unattached_request_photo(p_path text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT p_path IS NOT NULL
       AND (storage.foldername(p_path))[1] = auth.uid()::text
       AND NOT EXISTS (
           SELECT 1
             FROM public.complaint_attachments AS attachment
            WHERE attachment.storage_path = p_path
       )
       AND NOT EXISTS (
           SELECT 1
             FROM public.complaints AS complaint
            WHERE complaint."photo_path" = p_path
       )
       AND NOT EXISTS (
           SELECT 1
             FROM public.maintenance_requests AS request
            WHERE request."photo_path" = p_path
       )
$$;

